#!/usr/bin/env python3
"""Keep BENCHMARKS.md short by moving old entries into docs/benchmarks/.

    scripts/archive_benchmarks.py            # do it: keep the newest 2 dates in BENCHMARKS.md
    scripts/archive_benchmarks.py --check    # exit 1 if BENCHMARKS.md has outgrown its budget
    scripts/archive_benchmarks.py --keep 3   # keep the newest 3 distinct dates

BENCHMARKS.md is a log, newest first, and had grown to 7,500 lines: the
methodology at the top ("How to read these") is the part people need, and it
was under 375 KB of history. This keeps the methodology and the recent entries
where they are and moves the rest, unchanged and in the same order, to
docs/benchmarks/<year>-W<week>.md. A generated index in BENCHMARKS.md
lists every archived entry with a link, so nothing is harder to find than it was
by heading, and links of the form BENCHMARKS.md#<slug> elsewhere in the
repository are rewritten to the file the entry now lives in.

An entry is a `## ` heading through the line before the next one. The one edit
is that a relative link inside an archived entry gets `../../` in front, so it
still resolves from docs/benchmarks/ (and loses it again when read back). The
script re-reads what it wrote and refuses to finish unless the entries, taken
together, are byte-for-byte the entries it started with once that is undone.

Add new results to the top of BENCHMARKS.md as before. Run this when the file
gets long: --check fails once it passes MAX_ROOT_LINES, which is what CI runs.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BENCH = ROOT / "BENCHMARKS.md"
ARCHIVE = ROOT / "docs" / "benchmarks"
MAX_ROOT_LINES = 2000  # BENCHMARKS.md longer than this fails --check
INDEX_START = "<!-- archive-index:start (generated by scripts/archive_benchmarks.py) -->"
INDEX_END = "<!-- archive-index:end -->"
DATED = re.compile(r"^## (\d{4}-\d{2}-\d{2})\b")


def slug(heading: str) -> str:
    """GitHub's anchor for a heading: lowercase, punctuation dropped, spaces to hyphens."""
    text = heading.lstrip("# ").strip().lower()
    return re.sub(r"[^\w\- ]", "", text).replace(" ", "-")


FENCE = re.compile(r"^\s*(```|~~~)")
LINK_TARGET = re.compile(r"(\]\()([^)\s]+)")
DEPTH = "../../"  # docs/benchmarks/ is two levels below the repository root


def _retarget(lines: list[str], fix) -> list[str]:
    """Apply `fix` to the target of every Markdown link outside fenced code."""
    out, fenced = [], False
    for line in lines:
        if FENCE.match(line):
            fenced = not fenced
        out.append(line if fenced else LINK_TARGET.sub(lambda m: m.group(1) + fix(m.group(2)), line))
    return out


def _is_relative(target: str) -> bool:
    return not (target.startswith(("#", "/")) or re.match(r"^[a-z][a-z0-9+.\-]*:", target, re.I))


def shift(lines: list[str]) -> list[str]:
    """Root-relative links to links that work from docs/benchmarks/."""
    return _retarget(lines, lambda t: DEPTH + t if _is_relative(t) else t)


def unshift(lines: list[str]) -> list[str]:
    """The inverse of shift(): what a block looked like in BENCHMARKS.md."""
    return _retarget(lines, lambda t: t[len(DEPTH):] if t.startswith(DEPTH) else t)


def split(text: str) -> tuple[list[str], list[list[str]]]:
    """(lines before the first `## `, one list of lines per `## ` block)."""
    lines = text.split("\n")
    starts = [i for i, line in enumerate(lines) if line.startswith("## ")]
    if not starts:
        return lines, []
    blocks = [lines[a:b] for a, b in zip(starts, starts[1:] + [len(lines)])]
    return lines[: starts[0]], blocks


def date_of(block: list[str]) -> str | None:
    m = DATED.match(block[0])
    return m.group(1) if m else None


def parse_root() -> tuple[list[str], list[list[str]], list[list[str]]]:
    """(preamble, fixed blocks such as the methodology, dated blocks) of BENCHMARKS.md,
    with any generated index removed."""
    text = BENCH.read_text()
    if INDEX_START in text:
        head, _, rest = text.partition(INDEX_START)
        _, _, tail = rest.partition(INDEX_END)
        text = head.rstrip("\n") + "\n\n" + tail.lstrip("\n")
    pre, blocks = split(text)
    fixed = [b for b in blocks if date_of(b) is None]
    dated = [b for b in blocks if date_of(b) is not None]
    return pre, fixed, dated


def archive_files() -> list[Path]:
    """Existing archive files, newest first (their names sort by date)."""
    return sorted(ARCHIVE.glob("*.md"), reverse=True) if ARCHIVE.exists() else []


def read_archive(path: Path) -> tuple[list[str], list[list[str]]]:
    """An archive file's entries, in the root-relative form they had in BENCHMARKS.md."""
    pre, blocks = split(path.read_text())
    return pre, [unshift(b) for b in blocks]


def plan(dated: list[list[str]], keep: int) -> tuple[list[list[str]], list[list[str]]]:
    """(kept, to_move) by the `keep` newest distinct dates."""
    dates = sorted({date_of(b) for b in dated}, reverse=True)
    cutoff = set(dates[:keep])
    return [b for b in dated if date_of(b) in cutoff], [b for b in dated if date_of(b) not in cutoff]


def week_of(block: list[str]) -> str:
    """The ISO week an entry belongs to, e.g. 2026-W38. Archive files are named by it, so an
    entry's file never changes and adding one rewrites at most one file."""
    year, week, _ = date.fromisoformat(date_of(block)).isocalendar()
    return f"{year}-W{week:02d}"


def bucket(blocks: list[list[str]]) -> list[tuple[str, list[list[str]]]]:
    """[(file name, entries)] newest week first; entries keep their order."""
    weeks: dict[str, list[list[str]]] = {}
    for b in blocks:
        weeks.setdefault(week_of(b), []).append(b)
    return [(f"{w}.md", weeks[w]) for w in sorted(weeks, reverse=True)]


def archive_text(blocks: list[list[str]]) -> str:
    first, last = max(date_of(b) for b in blocks), min(date_of(b) for b in blocks)
    head = (
        f"# Benchmark history, week {week_of(blocks[0])} ({last} to {first})\n\n"
        "Archived from [BENCHMARKS.md](../../BENCHMARKS.md), unchanged and in the same order "
        "(newest first). Read [How to read these](../../BENCHMARKS.md#how-to-read-these) "
        "before comparing any two numbers here; the rule is the same as ever: compare rows "
        "within a table, never across tables.\n\n"
    )
    return head + "\n".join("\n".join(shift(b)) for b in blocks).rstrip("\n") + "\n"


def index_text(files: list[tuple[str, list[list[str]]]]) -> str:
    out = [INDEX_START, "", "## Earlier entries", "",
           "Moved to `docs/benchmarks/` to keep this file readable; unchanged. "
           "`scripts/archive_benchmarks.py` does the moving.", ""]
    for name, blocks in files:
        dates = sorted(date_of(b) for b in blocks)
        out.append(f"### [{name[:-3]}](docs/benchmarks/{name}), {dates[0]} to {dates[-1]}")
        out.append("")
        for b in blocks:
            title = b[0][3:].strip()
            out.append(f"- [{title}](docs/benchmarks/{name}#{slug(b[0])})")
        out.append("")
    out.append(INDEX_END)
    return "\n".join(out) + "\n"


def rewrite_links(mapping: dict[str, str]) -> list[str]:
    """Point BENCHMARKS.md#<slug> links at the archive file that now holds the entry."""
    changed = []
    pattern = re.compile(r"\(((?:\.\./)*)BENCHMARKS\.md#([\w\-]+)\)")
    for path in ROOT.rglob("*.md"):
        if any(part in {".git", "target", "node_modules"} for part in path.parts):
            continue
        if path == BENCH or ARCHIVE in path.parents:
            continue
        text = path.read_text()

        def fix(m: re.Match) -> str:
            target = mapping.get(m.group(2))
            if not target:
                return m.group(0)
            rel = path.parent.relative_to(ROOT).parts
            prefix = "../" * len(rel)
            return f"({prefix}docs/benchmarks/{target}#{m.group(2)})"

        new = pattern.sub(fix, text)
        if new != text:
            path.write_text(new)
            changed.append(str(path.relative_to(ROOT)))
    return changed


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--keep", type=int, default=2, help="distinct dates to keep in BENCHMARKS.md")
    ap.add_argument("--check", action="store_true", help="only report whether anything should move")
    args = ap.parse_args()

    pre, fixed, dated = parse_root()
    kept, moving = plan(dated, args.keep)
    if args.check:
        n = len(BENCH.read_text().split("\n"))
        if n > MAX_ROOT_LINES:
            print(f"BENCHMARKS.md is {n} lines (budget {MAX_ROOT_LINES}); "
                  "run scripts/archive_benchmarks.py")
            return 1
        print(f"BENCHMARKS.md is {n} lines, within its budget of {MAX_ROOT_LINES}")
        return 0
    if not moving:
        print("nothing to move")
        return 0

    # What the archive holds already, newest first, plus what is moving now.
    existing: list[list[str]] = []
    for path in archive_files():
        existing += read_archive(path)[1]
    everything = moving + existing  # moving entries are newer than anything archived
    before = sorted("\n".join(b) for b in everything + kept + fixed)

    ARCHIVE.mkdir(parents=True, exist_ok=True)
    for path in archive_files():
        path.unlink()
    files = bucket(everything)
    for name, g in files:
        (ARCHIVE / name).write_text(archive_text(g))

    body = "\n".join(pre).rstrip("\n") + "\n\n"
    body += "\n".join("\n".join(b) for b in fixed).rstrip("\n") + "\n\n"
    body += "\n".join("\n".join(b) for b in kept).rstrip("\n") + "\n\n"
    body += index_text(files)
    BENCH.write_text(body)

    # Prove it: every entry that went in is in exactly one place, unchanged.
    _, fixed2, dated2 = parse_root()
    after_blocks = list(fixed2) + list(dated2)
    for name, _ in files:
        after_blocks += read_archive(ARCHIVE / name)[1]
    after = sorted("\n".join(b).rstrip("\n") for b in after_blocks)
    if after != [x.rstrip("\n") for x in before]:
        print("FAILED: the entries after the move are not the entries before it", file=sys.stderr)
        return 1

    mapping = {slug(b[0]): name for name, g in files for b in g}
    changed = rewrite_links(mapping)
    print(f"kept {len(kept)} entries in BENCHMARKS.md; archived {len(everything)} in "
          f"{len(files)} files; rewrote links in: {', '.join(changed) or 'no file'}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
