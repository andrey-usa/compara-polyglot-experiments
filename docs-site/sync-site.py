#!/usr/bin/env python3
"""Sync the three products' docs into the Starlight site (T-0083).

Sources of truth (checked out at pinned refs, passed as --<product> dirs):
  navigera master, compara main, primavera next.
Each product's README becomes its overview page, docs/ and SKILL.md become
guide pages, CHANGELOG becomes the changelog page. Repo-relative links
that point at a page included in the site are rewritten to that site
page; every other repo-relative link is rewritten to the file on GitHub
at the product's branch, so the built site has no dangling internal
links. Empty table-header cells (axe empty-table-header hits) are filled
with a header derived from the table's rows.

Pages the script writes are marked "generated by sync-site.py" in a
comment; hand-written pages (landing, install, quickstart) are never
touched. Run from docs-site/:

  python3 sync-site.py --navigera DIR --compara DIR --primavera DIR

Writes a JSON report to stdout (pages, links rewritten, headers fixed).
"""
import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent
STAR = ROOT / "starlight" / "src" / "content" / "docs"

LINK_RE = re.compile(r"(!?)\[([^\]]*)\]\(([^)\s]+)(?:\s+\"[^\"]*\")?\)")
FRONTMATTER_RE = re.compile(r"\A---\n.*?\n---\n", re.DOTALL)


def strip_frontmatter(text):
    return FRONTMATTER_RE.sub("", text, count=1)


def first_h1(text):
    body = strip_frontmatter(text)
    for line in body.splitlines():
        if line.startswith("# "):
            return line[2:].strip().strip("`")
    return ""


def first_para(text):
    body = strip_frontmatter(text)
    # first non-heading, non-blank, non-badge paragraph line
    for line in body.splitlines():
        s = line.strip()
        if not s or s.startswith(("#", "![", "[![", ">", "```", "|", "- ")):
            continue
        s = re.sub(r"[`*_]", "", s)
        return s[:160]
    return ""


def frontmatter(title, body):
    desc = first_para(body) or title
    desc = '"' + desc.replace("\\", "\\\\").replace('"', '\\"') + '"'
    return f"---\ntitle: {title}\ndescription: {desc}\n---\n"


def write_page(rel, title, body):
    path = STAR / rel
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(frontmatter(title, body) + strip_frontmatter(body).lstrip("\n"),
                    encoding="utf-8")
    return str(path.relative_to(ROOT))


# (substring found in the table's first data row) -> header labels
HEADER_FIXES = [
    ("npm install -g navigera", ["Channel", "Command"]),
    ("cargo install --locked compara", ["Channel", "Command"]),
    ("start --attach", ["Way", "the agent gets", "needs"]),
    ("--attach chrome", ["Way", "what it connects to", "closes the browser?"]),
    ("TYPESAFE_API_KEY", ["variable", "Value"]),
    ("element choice right", ["Measure", "Jev", "Gemini 3.5 Flash-Lite"]),
    ("starts-with", ["expect", "Meaning"]),
]


def fix_table_headers(text, log):
    """Fill empty header cells in markdown tables."""
    lines = text.splitlines()
    out = []
    i = 0
    while i < len(lines):
        line = lines[i]
        if (line.startswith("|") and i + 2 < len(lines)
                and re.match(r"^\|[\s:|-]+\|\s*$", lines[i + 1])):
            cells = [c.strip() for c in line.strip().strip("|").split("|")]
            if any(c == "" for c in cells):
                first_row = lines[i + 2]
                labels = None
                for needle, labs in HEADER_FIXES:
                    if needle in first_row:
                        labels = labs
                        break
                if labels is None:
                    labels = ["Item" if j == 0 else "Detail"
                              for j in range(len(cells))]
                fixed = [c if c else labels[j] for j, c in enumerate(cells)]
                log.append(f"header {' | '.join(cells)} -> {' | '.join(fixed)}")
                line = "| " + " | ".join(fixed) + " |"
        out.append(line)
        i += 1
    return "\n".join(out) + "\n"


def fix_links(text, product, site_pages, log, src_dir=""):
    """Rewrite repo-relative links: site page if included, else GitHub.

    Targets resolve against the source file's directory, so
    docs/navigera.md's ../skills/... and README's .github/... both land
    on their repo-root-relative path (the leading dot is significant).
    """
    import posixpath
    gh = {"navigera": "https://github.com/andrey-usa/navigera/blob/master/",
          "compara": "https://github.com/andrey-usa/compara/blob/main/",
          "primavera": "https://github.com/andrey-usa/primavera/blob/next/"}[product]

    def repl(m):
        bang, label, target = m.group(1), m.group(2), m.group(3)
        if target.startswith(("http://", "https://", "mailto:", "#")) or bang:
            return m.group(0)
        path, _, frag = target.partition("#")
        path = posixpath.normpath(posixpath.join(src_dir, path))
        if path in site_pages:
            new = site_pages[path] + (f"#{frag}" if frag else "")
            log.append(f"site link: {target} -> {new}")
            return f"{bang}[{label}]({new})"
        if not path:
            return m.group(0)
        new = gh + path + (f"#{frag}" if frag else "")
        log.append(f"github link: {target} -> {new}")
        return f"{bang}[{label}]({new})"

    return LINK_RE.sub(repl, text)


def extract_sections(text, headings):
    """Extract README sections by heading text (kept in order)."""
    lines = strip_frontmatter(text).splitlines()
    out, cur, keep = [], None, False
    for line in lines:
        m = re.match(r"^(#{1,3})\s+(.*)$", line)
        if m:
            keep = m.group(2).strip() in headings
            cur = m.group(2).strip() if keep else None
            if keep:
                out.append(line)
            continue
        if keep:
            out.append(line)
    return "\n".join(out).strip() + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--navigera", required=True)
    ap.add_argument("--compara", required=True)
    ap.add_argument("--primavera", required=True)
    args = ap.parse_args()
    src = {"navigera": Path(args.navigera), "compara": Path(args.compara),
           "primavera": Path(args.primavera)}

    # site-internal targets: repo-relative path -> site URL
    site_pages = {
        "navigera": {"README.md": "/navigera/", "CHANGELOG.md": "/navigera/changelog/",
                    "docs/navigera.md": "/navigera/reference/",
                    "docs/multi-model.md": "/navigera/multi-model/",
                    "skills/navigera/SKILL.md": "/navigera/skill/",
                    "llms.txt": "/navigera/llms/",
                    "CONTRIBUTING.md": "/navigera/contributing/"},
        "compara": {"README.md": "/compara/", "CHANGELOG.md": "/compara/changelog/",
                    "docs/contract.schema.json": "/compara/contract/",
                    "CONTRIBUTING.md": "/compara/contributing/"},
        "primavera": {"README.md": "/primavera/",
                      "skills/primavera/SKILL.md": "/primavera/skill/"},
    }

    report = {"pages": [], "links": [], "headers": []}
    def sync(product, src_rel, dest, title):
        raw = (src[product] / src_rel).read_text(encoding="utf-8")
        src_dir = src_rel.rsplit("/", 1)[0] if "/" in src_rel else ""
        body = fix_links(raw, product, site_pages[product], report["links"],
                         src_dir=src_dir)
        body = fix_table_headers(body, report["headers"])
        report["pages"].append(write_page(dest, title, body))

    # navigera
    sync("navigera", "README.md", "navigera/index.md", "navigera")
    sync("navigera", "docs/navigera.md", "navigera/reference.md", "navigera reference")
    sync("navigera", "docs/multi-model.md", "navigera/multi-model.md", "navigera multi-model")
    sync("navigera", "skills/navigera/SKILL.md", "navigera/skill.md", "navigera agent skill")
    sync("navigera", "CHANGELOG.md", "navigera/changelog.md", "navigera changelog")
    sync("navigera", "llms.txt", "navigera/llms.md", "navigera llms.txt")
    sync("navigera", "CONTRIBUTING.md", "navigera/contributing.md", "navigera contributing")
    # compara
    sync("compara", "README.md", "compara/index.md", "compara")
    sync("compara", "CHANGELOG.md", "compara/changelog.md", "compara changelog")
    sync("compara", "CONTRIBUTING.md", "compara/contributing.md", "compara contributing")
    readme = (src["compara"] / "README.md").read_text(encoding="utf-8")
    guides = extract_sections(readme, ["Cloud and containers", "Speed", "Engines"])
    guides = fix_links(guides, "compara", site_pages["compara"], report["links"])
    guides = fix_table_headers(guides, report["headers"])
    report["pages"].append(write_page("compara/guides.md", "compara guides", guides))
    schema = (src["compara"] / "docs/contract.schema.json").read_text(encoding="utf-8")
    report["pages"].append(write_page(
        "compara/contract.md", "compara report JSON contract",
        "# Report JSON contract\n\nThe `--json` summary schema "
        "(`docs/contract.schema.json`):\n\n```json\n" + schema + "```\n"))
    # primavera (no CHANGELOG.md in repo: the changelog page is hand-written)
    sync("primavera", "README.md", "primavera/index.md", "primavera")
    sync("primavera", "skills/primavera/SKILL.md", "primavera/skill.md", "primavera agent skill")
    print(json.dumps(report, indent=2))
    return 0


if __name__ == "__main__":
    sys.exit(main())
